from enum import Enum


class APCErrorCode(str, Enum):
    INVALID_MODEL = "INVALID_MODEL"
    INVALID_CANONICAL_DATA = "INVALID_CANONICAL_DATA"
    INVALID_SIGNATURE = "INVALID_SIGNATURE"
    EXPIRED_AUTHORITY = "EXPIRED_AUTHORITY"
    REVOKED_AUTHORITY = "REVOKED_AUTHORITY"
    REPLAYED_AUTHORITY = "REPLAYED_AUTHORITY"
    DIGEST_MISMATCH = "DIGEST_MISMATCH"
    ACTOR_MISMATCH = "ACTOR_MISMATCH"
    AUDIENCE_MISMATCH = "AUDIENCE_MISMATCH"
    INVALID_AUTHORITY = "INVALID_AUTHORITY"
    CONSTRAINT_VIOLATION = "CONSTRAINT_VIOLATION"
    INVALID_EVIDENCE = "INVALID_EVIDENCE"
    EVIDENCE_CHAIN_BROKEN = "EVIDENCE_CHAIN_BROKEN"
    FRESHNESS_VIOLATION = "FRESHNESS_VIOLATION"
    POLICY_STATE_INVALID = "POLICY_STATE_INVALID"
    WORKLOAD_TRUST_INVALID = "WORKLOAD_TRUST_INVALID"
    SINK_CONTRACT_INVALID = "SINK_CONTRACT_INVALID"
    PRECONDITION_FAILED = "PRECONDITION_FAILED"
    PROTOCOL_VERSION_INVALID = "PROTOCOL_VERSION_INVALID"
    SCHEMA_VERSION_INVALID = "SCHEMA_VERSION_INVALID"
    CANONICALIZATION_VERSION_INVALID = "CANONICALIZATION_VERSION_INVALID"
    CRYPTO_DOMAIN_INVALID = "CRYPTO_DOMAIN_INVALID"
    CONTRACT_INVALID = "CONTRACT_INVALID"
    CONTRACT_VIOLATION = "CONTRACT_VIOLATION"
    TRANSITION_NOT_ALLOWED = "TRANSITION_NOT_ALLOWED"
    TRANSITION_ORDER_INVALID = "TRANSITION_ORDER_INVALID"
    CHAIN_MISMATCH = "CHAIN_MISMATCH"
    CHAIN_LOOP = "CHAIN_LOOP"
    CHAIN_PAUSED = "CHAIN_PAUSED"
    CHAIN_ABORTED = "CHAIN_ABORTED"
    NODE_DISABLED = "NODE_DISABLED"
    DELEGATION_INVALID = "DELEGATION_INVALID"
    WITNESS_INVALID = "WITNESS_INVALID"
    ASSURANCE_UNAVAILABLE = "ASSURANCE_UNAVAILABLE"
    ASSURANCE_INVALID = "ASSURANCE_INVALID"
    ASSURANCE_EXPIRED = "ASSURANCE_EXPIRED"
    STATE_UNAVAILABLE = "STATE_UNAVAILABLE"
    CONTINUITY_VIOLATION = "CONTINUITY_VIOLATION"


class APCError(Exception):
    def __init__(self, code: APCErrorCode, message: str):
        self.code = code
        self.message = message
        super().__init__(f"[{code.value}] {message}")
